    /** Builds a dictionary from entries ordered least common -> most common. Int, Boolean and String only. Max 32 KB. */
    fun build(entries: List<Any>): ByteArray {
        val out = ByteBuffers.Out()
        for (e in entries) when (e) {
            is Int -> out.writeInt(e)
            is Boolean -> out.writeBoolean(e)
            is String -> out.writeUTF(e)
            else -> error("Unsupported dictionary entry: $e")
        }
        val bytes = out.toByteArray()
        // zlib only uses the last 32 KB, so drop the front (least common) if too large
        return if (bytes.size > 32768) bytes.copyOfRange(bytes.size - 32768, bytes.size) else bytes
    }

